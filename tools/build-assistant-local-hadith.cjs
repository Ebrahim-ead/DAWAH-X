#!/usr/bin/env node
'use strict';
// Locate displayed hadith numbers in the site's two newer local books.
// Only positions are bundled; each answer is reloaded from the actual reader
// shard, validated and attributed. Never bundle a generated religious answer.
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),zlib=require('node:zlib');
const root=path.resolve(__dirname,'..'),ctx={window:{}};
vm.runInNewContext(fs.readFileSync(path.join(root,'scripture-hadith-index.js'),'utf8'),ctx,{timeout:1000});
const books=ctx.window.HADITH_INDEX?.books,result={};
for(const id of ['malik','nawawi']){
 const b=books?.[id];if(!b||typeof b.bn!=='string'||!Array.isArray(b.sections))throw Error('Invalid book '+id);
 const entries={};let total=0;
 for(const sec of b.sections.filter(s=>s.count)){
  if(!Number.isInteger(sec.id)||sec.id<0||sec.id>200)throw Error('Invalid section');
  const rows=JSON.parse(zlib.gunzipSync(fs.readFileSync(path.join(root,`scripture-hadith-${id}-${sec.id}.json.gz`))));
  if(!Array.isArray(rows)||rows.length!==sec.count)throw Error('Invalid section length');
  for(const r of rows){if(!Array.isArray(r)||r.length!==8||!Number.isInteger(r[0])||r[0]<1||!Number.isInteger(r[1])||r[1]<1||r[1]>20000||entries[r[1]])throw Error('Invalid or ambiguous hadith number');entries[r[1]]=[sec.id,r[0]];total++}
 }
 if(total!==b.total)throw Error('Invalid book total');result[id]={title:b.bn,entries};
}
const output='/* Generated by tools/build-assistant-local-hadith.cjs; positions only, not religious text. */\nexport default '+JSON.stringify(result)+';\n';
const target=path.join(root,'ai-worker/local-hadith-locator.mjs');
if(process.argv.includes('--check')){if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==output){console.error('Local hadith locator is out of date');process.exitCode=1}}else fs.writeFileSync(target,output);
