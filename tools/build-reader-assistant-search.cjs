#!/usr/bin/env node
'use strict';
// Reader pages use a separate shell. Build their search from the exact main
// site's implementation, without mounting app.js's unrelated UI handlers.
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..'),app=fs.readFileSync(path.join(root,'app.js'),'utf8');
const start=app.indexOf('const FOLD_MAP='),end=app.indexOf('/* ===== /মিলে-যাওয়া লেখা ও ভিডিও ===== */',start);
if(start<0||end<0)throw Error('Assistant search boundaries missing');
const output='/* Generated by tools/build-reader-assistant-search.cjs from app.js; do not edit. */\n(()=>{\n"use strict";\nconst BN_DIGITS="০১২৩৪৫৬৭৮৯";\nconst toLatinDigits=v=>String(v).replace(/[০-৯]/g,d=>String(BN_DIGITS.indexOf(d)));\n'+app.slice(start,end)+'\nwindow.dawahxAssistantSearch=q=>assistantSearch(q);\n})();\n';
const target=path.join(root,'reader-assistant-search.js');
if(process.argv.includes('--check')){if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==output){console.error('Reader assistant search is out of date');process.exitCode=1}}else fs.writeFileSync(target,output);
