#!/usr/bin/env node
'use strict';
// Build the reader's Ebrahim Ead edition from a checked-out source revision.
// Input is NOT fetched here. Never infer a hadith number or invent a grade.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto'),zlib=require('node:zlib');
const dir=process.argv[2], revision=process.argv[3];
if(!dir || !/^[0-9a-f]{40}$/.test(revision||'')) throw Error('Usage: node tools/build-ead-hadith.cjs <assets/hadith/data> <source commit>');
const idx=JSON.parse(fs.readFileSync(path.join(dir,'index.json'))), expected=['bukhari','muslim','nasai','abu-dawud','tirmidhi','ibn-majah','mishkat'];
if(JSON.stringify(idx.books.map(x=>x.slug))!==JSON.stringify(expected))throw Error('Unexpected source book list');
const aliases={'abu-dawud':'abudawud','ibn-majah':'ibnmajah'}, en={bukhari:'Sahih al-Bukhari',muslim:'Sahih Muslim',nasai:'Sunan an-Nasai','abu-dawud':'Sunan Abu Dawud',tirmidhi:'Jami at-Tirmidhi','ibn-majah':'Sunan Ibn Majah',mishkat:'Mishkat al-Masabih'};
const books={},grade={daif:[],mawdu:[]}, shards=[], counts={};let all=0;
for(const b of idx.books){
 const id=aliases[b.slug]||b.slug, sections=[];let serial=0;
 for(const c of b.chapters){
  const src=JSON.parse(fs.readFileSync(path.join(dir,b.slug,c.id+'.json')));
  if(src.book!==b.slug||src.chapter!==c.id||!Array.isArray(src.verses)||src.verses.length!==c.count)throw Error('Bad chapter '+b.slug+':'+c.id);
  const first=serial+1;
  const rows=src.verses.map(v=>{
   if(!Number.isInteger(v.i)||v.i<1||typeof v.b!=='string'||!v.b.trim()||typeof v.a!=='string'||typeof v.g!=='string')throw Error('Bad source record '+b.slug+':'+v.i);
   const row=[++serial,v.i,'',v.b,v.a,'',v.n||'',v.g,v.no||v.tah||'',v.dup||0,v.s||''];
   if(/জাল|মাওদু|মাওযূ/.test(v.g))grade.mawdu.push([id,serial,c.id,v.i,v.g]);
   else if(/দুর্বল|যঈফ/.test(v.g))grade.daif.push([id,serial,c.id,v.i,v.g]);
   return row;
  });
  const raw=Buffer.from(JSON.stringify(rows));const file=`scripture-hadith-${id}-${c.id}.json.gz`;
  fs.writeFileSync(file,zlib.gzipSync(raw,{level:9,mtime:0}));
  shards.push({book:id,section:c.id,count:rows.length,sha256:crypto.createHash('sha256').update(raw).digest('hex'),file});
  sections.push({id:c.id,name:c.bn,count:rows.length,first,last:serial,hadithFirst:c.from,hadithLast:c.to});
 }
 if(serial!==b.count)throw Error('Source count mismatch '+b.slug);counts[id]=serial;all+=serial;
 books[id]={bn:b.bn,short:b.short,ar:b.ar,en:en[b.slug],edition:b.slug==='mishkat'?'মুসলিম বাংলা':'আল-হাদিস',site:`https://ebrahim-ead.github.io/ead/hadith.html#${b.slug}:1`,source:b.slug==='mishkat'?'mishkat':'ihadis',slug:b.slug,id,total:serial,shards:sections.length,langs:{bn:true,ar:true,en:false},sections};
}
if(all!==40349)throw Error('Source total mismatch');
const output={version:'ead-1',fields:['i','n','an','bn','ar','en','r','g','note','dup','sectionTitle'],source:{dataset:'Ebrahim-ead/ead',revision},books};
fs.writeFileSync('scripture-hadith-index.js','/* Generated by tools/build-ead-hadith.cjs. Source revision '+revision+'. */\nwindow.HADITH_DATA='+JSON.stringify(Object.fromEntries(Object.keys(books).map(k=>[k,{}])))+';\nwindow.HADITH_INDEX='+JSON.stringify(output)+';\nwindow.HADITH_GRADE_INDEX='+JSON.stringify(grade)+';\n');
fs.writeFileSync('scripture-manifest.json',JSON.stringify({source:'https://github.com/Ebrahim-ead/ead',revision,total:all,books:counts,shards}));
console.log('Built',all,'records',shards.length,'chapters, weak',grade.daif.length,'fabricated',grade.mawdu.length);
